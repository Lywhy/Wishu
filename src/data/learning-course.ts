export function courseSteps(section: QuestionSection, questions: Question[]): LearningStep[] {
  const plan = plans[section.id]
  if (plan)
    return plan.flatMap(([id, title, ids, markdown]) => [
      { id: id + "-lecture", title, kind: "lecture" as const, markdown, tasks: [] },
      {
        id: id + "-practice",
        title: "Практика: " + title.toLocaleLowerCase("ru"),
        kind: "practice" as const,
        tasks: ids.flatMap((id) => {
          const task = practiceTasks.find((item) => item.id === id)
          return task ? [task] : []
        }),
      },
    ])
  return section.subsections.flatMap((sub) => {
    const entries = sub.questionIds
      .flatMap((id) => {
        const item = questions.find((q) => q.id === id)
        return item ? [item] : []
      })
      .slice(0, 3)
    if (!entries.length) return []
    const markdown =
      "## " +
      sub.title +
      "\n\n" +
      sub.description +
      "\n\n" +
      entries
        .map(
          (q, i) =>
            "### " +
            q.title +
            "\n\n" +
            q.answer.join("\n\n") +
            "\n\n> **Запомните:** " +
            q.takeaway +
            (q.pitfall ? "\n\n**Частая ошибка:** " + q.pitfall : "") +
            (q.code ? "\n\n\x60\x60\x60javascript\n" + q.code + "\n\x60\x60\x60" : "") +
            (i === 0
              ? "\n\nПримечание к примерам.[^environment]\n\n[^environment]: Примеры иллюстрируют механизм; учитывайте окружение выполнения."
              : ""),
        )
        .join("\n\n") +
      "\n\n### Проверьте понимание\n\n" +
      entries.map((q) => "- " + q.summary).join("\n")
    return [
      { id: sub.id + "-lecture", title: sub.title, kind: "lecture" as const, markdown, tasks: [] },
    ]
  })
}
export const stepKey = (sectionId: string, stepId: string) => sectionId + ":" + stepId

export function stepCompleted(sectionId: string, step: LearningStep, completed: string[]) {
  const key = stepKey(sectionId, step.id)
  return step.kind === "lecture"
    ? completed.includes(key)
    : step.tasks.length > 0 && step.tasks.every((task) => completed.includes(key + ":" + task.id))
}
